void write_header(FILE *fp)
{
    fprintf(fp, "%% Auto-generated Prolog crossword (step2.pl)\n");
    fprintf(fp, "%% Generated by generator.c\n\n");
}

void write_helper_predicates(FILE *fp)
{
    fprintf(fp,
            "nth(0, [X|_], X).\n"
            "nth(N, [_|T], X) :- N > 0, N1 is N - 1, nth(N1, T, X).\n\n"

            "all_unique([]).\n"
            "all_unique([X|Xs]) :- \\+ member(X, Xs), all_unique(Xs).\n\n"

            "write_word(_, []).\n"
            "write_word(S, [C|Rest]) :- write(S, C), write_word(S, Rest).\n\n"

            "print_slot(S, Word, SlotName) :-\n"
            "    slot(SlotName, _, R, C),\n"
            "    write(S, SlotName), write(S, ' '),\n"
            "    write(S, R), write(S, ' '), write(S, C), write(S, ' '),\n"
            "    write_word(S, Word), nl(S).\n\n");
}

void write_word_facts(FILE *fp, char words[][MAX_WORD_LEN], int count)
{
    for (int i = 0; i < count; i++)
    {
        fprintf(fp, "word([");
        for (int j = 0; words[i][j] != '\0'; j++)
        {
            if (words[i][j] == '\'')
            {
                fprintf(fp, "'\\''");
            }
            else
            {
                fprintf(fp, "'%c'", words[i][j]);
            }
            if (words[i][j + 1] != '\0')
                fprintf(fp, ",");
        }
        fprintf(fp, "]).\n");
    }
    fprintf(fp, "\n");
}

void write_slot_facts(FILE *fp, Slot H[], int hcount, Slot V[], int vcount)
{
    for (int i = 0; i < hcount; i++)
        fprintf(fp, "slot(h%d, horizontal, %d, %d).\n",
                H[i].id, H[i].row, H[i].col);

    for (int i = 0; i < vcount; i++)
        fprintf(fp, "slot(v%d, vertical, %d, %d).\n",
                V[i].id, V[i].row, V[i].col);

    fprintf(fp, "\n");
}

void write_crossword_head(FILE *fp, int hcount, int vcount)
{
    fprintf(fp, "crossword(");
    int first = 1;
    for (int i = 0; i < hcount; i++)
    {
        if (!first)
            fprintf(fp, ",");
        fprintf(fp, "H%d", i);
        first = 0;
    }
    for (int i = 0; i < vcount; i++)
    {
        if (!first)
            fprintf(fp, ",");
        fprintf(fp, "V%d", i);
        first = 0;
    }
    fprintf(fp, ") :-\n");
}

void write_length_constraints(FILE *fp, Slot H[], int hcount, Slot V[], int vcount)
{
    for (int i = 0; i < hcount; i++)
        fprintf(fp, "    length(H%d,%d),\n", i, H[i].length);
    for (int i = 0; i < vcount; i++)
        fprintf(fp, "    length(V%d,%d),\n", i, V[i].length);
}

void write_word_constraints(FILE *fp, int hcount, int vcount)
{
    for (int i = 0; i < hcount; i++)
        fprintf(fp, "    word(H%d),\n", i);
    for (int i = 0; i < vcount; i++)
        fprintf(fp, "    word(V%d),\n", i);
}

void generate_intersections(FILE *fp, Slot H[], int hcount, Slot V[], int vcount)
{
    int varCounter = 0;
    for (int hi = 0; hi < hcount; hi++)
    {
        Slot HS = H[hi];
        for (int vi = 0; vi < vcount; vi++)
        {
            Slot VS = V[vi];
            for (int hpos = 0; hpos < HS.length; hpos++)
            {
                int Hr = HS.row;
                int Hc = HS.col + hpos;
                for (int vpos = 0; vpos < VS.length; vpos++)
                {
                    int Vr = VS.row + vpos;
                    int Vc = VS.col;
                    if (Hr == Vr && Hc == Vc)
                    {
                        fprintf(fp,
                                "    nth(%d, H%d, X%d), nth(%d, V%d, X%d),\n",
                                hpos, HS.id, varCounter,
                                vpos, VS.id, varCounter);
                        varCounter++;
                    }
                }
            }
        }
    }
}

