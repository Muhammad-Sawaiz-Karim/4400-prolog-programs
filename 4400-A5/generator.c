void write_crossword_head(FILE *fp, int hcount, int vcount);
void write_length_constraints(FILE *fp, Slot H[], int hcount, Slot V[], int vcount);
void write_word_constraints(FILE *fp, int hcount, int vcount);
void generate_intersections(FILE *fp, Slot H[], int hcount, Slot V[], int vcount);
void write_unique_constraint(FILE *fp, int hcount, int vcount);
void write_crossword_tail(FILE *fp);
void write_solve_predicate(FILE *fp, int hcount, int vcount);
void read_words(const char *word_file, char words[MAX_WORDS][MAX_WORD_LEN], int *word_count);
void read_pattern(const char *pattern_file, int grid[100][100], int *rows, int *cols);
