void read_words(const char *word_file, char words[MAX_WORDS][MAX_WORD_LEN], int *word_count)
{
    FILE *word_p = fopen(word_file, "r");
    if (word_p == NULL)
    {
        perror("Error opening words file");
        exit(1);
    }
    int i = 0;
    char buffer[MAX_WORD_LEN];
    while (i < MAX_WORDS && fscanf(word_p, "%s", buffer) == 1)
    {
        strcpy(words[i], buffer);
        i++;
    }
    *word_count = i;
    fclose(word_p);
}

void read_pattern(const char *pattern_file, int grid[100][100], int *rows, int *cols)
{
    FILE *pattern_p = fopen(pattern_file, "r");
    if (pattern_p == NULL)
    {
        perror("Error opening pattern file");
        exit(1);
    }
    int row_count = 0;
    int col_count = 0;
    int width = 0;
    int ch;
    while ((ch = fgetc(pattern_p)) != EOF)
    {
        if (ch == '0' || ch == '1')
        {
            grid[row_count][col_count] = ch - '0';
            col_count++;
        }
        else if (ch == '\n')
        {
            if (col_count > width)
                width = col_count;
            if (col_count > 0)
                row_count++;
            col_count = 0;
        }
    }
    if (col_count > 0)
    {
        if (col_count > width)
            width = col_count;
        row_count++;
    }
    *rows = row_count;
    *cols = width;
    fclose(pattern_p);
}

int slots(int grid[100][100], Slot H_slots[500], Slot V_slots[500], int rows, int cols)
{
    int hcount = 0;
    int vcount = 0;
    for (int r = 0; r < rows; r++)
    {
        int c = 0;
        while (c < cols)
        {
            if (grid[r][c] == 1)
            {
                int start = c;
                int len = 0;
                while (c < cols && grid[r][c] == 1)
                {
                    len++;
                    c++;
                }
                if (len >= 2)
                {
                    H_slots[hcount].id = hcount;
                    H_slots[hcount].row = r;
                    H_slots[hcount].col = start;
                    H_slots[hcount].length = len;
                    H_slots[hcount].dir = 0;
                    hcount++;
                }
            }
            else
            {
                c++;
            }
        }
    }
    for (int c = 0; c < cols; c++)
    {
        int r = 0;
        while (r < rows)
        {
            if (grid[r][c] == 1)
            {
                int start = r;
                int len = 0;
                while (r < rows && grid[r][c] == 1)
                {
                    len++;
                    r++;
                }
                if (len >= 2)
                {
                    V_slots[vcount].id = vcount;
                    V_slots[vcount].row = start;
                    V_slots[vcount].col = c;
                    V_slots[vcount].length = len;
                    V_slots[vcount].dir = 1;
                    vcount++;
                }
            }
            else
            {
                r++;
            }
        }
    }
    return (hcount << 16) | (vcount & 0xFFFF);
}

int main(int argc, char *argv[])
{
    if (argc < 3)
    {
        fprintf(stderr, "Usage: %s words.txt binpattern.txt\n", argv[0]);
        return 1;
    }
    char *word_file = argv[1];
    char *pattern_file = argv[2];

    char words[MAX_WORDS][MAX_WORD_LEN];
    int grid[100][100] = {{0}};
    Slot H[500];
    Slot V[500];
    int word_count = 0;
    int rows = 0;
    int cols = 0;
    int hcount = 0;
    int vcount = 0;

    read_words(word_file, words, &word_count);
    read_pattern(pattern_file, grid, &rows, &cols);

    int packed = slots(grid, H, V, rows, cols);
    hcount = (packed >> 16) & 0xFFFF;
    vcount = packed & 0xFFFF;

    FILE *fp = fopen("step2.pl", "w");
    if (fp == NULL)
    {
        perror("Error creating step2.pl");
        return 1;
    }

    write_header(fp);
    write_helper_predicates(fp);
    write_word_facts(fp, words, word_count);
    write_slot_facts(fp, H, hcount, V, vcount);
    write_crossword_head(fp, hcount, vcount);
    write_length_constraints(fp, H, hcount, V, vcount);
    write_word_constraints(fp, hcount, vcount);
    generate_intersections(fp, H, hcount, V, vcount);
    write_unique_constraint(fp, hcount, vcount);
    write_crossword_tail(fp);
    write_solve_predicate(fp, hcount, vcount);

    fclose(fp);
    printf("Generated step2.pl: %d words, %d horizontal, %d vertical, grid %dx%d\n",
           word_count, hcount, vcount, rows, cols);

    return 0;
}